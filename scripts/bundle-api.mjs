#!/usr/bin/env node
/**
 * Bundle the Hono API + game package into a single Vercel serverless file.
 * Avoids fragile includeFiles / workspace resolution on Hobby.
 */
import * as esbuild from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const gameEntry = path.join(root, "packages/game/src/index.ts");

await esbuild.build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "apps/server/src/vercel-entry.ts")],
  outfile: path.join(root, "api/index.js"),
  bundle: true,
  platform: "node",
  target: "node20",
  format: "cjs",
  sourcemap: false,
  logLevel: "info",
  alias: {
    "@starhold/game": gameEntry,
  },
  banner: {
    js: "/* starhold api bundle — generated by scripts/bundle-api.mjs */\n",
  },
  // Vercel Node looks for module.exports / exports as the handler, not .default.
  footer: {
    js: "\nmodule.exports = module.exports.default;\n",
  },
});

console.log("Bundled api/index.js for Vercel");
